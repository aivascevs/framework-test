"""Shared helpers for the governance scripts: specification front matter, the
permitted-file list (section 7), path globs and risk classes. Needs PyYAML.
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

import yaml

RISK_CLASSES = ["Routine", "Elevated", "High impact", "Restricted"]
FRONT_MATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*(?:\n|\Z)", re.S)


def glob_to_regex(pattern: str) -> re.Pattern:
    """'**/' matches zero or more folders, '**' anything, '*' and '?' stay inside one folder."""
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile("^" + out + "$")


def matches(path: str, patterns: list[str]) -> str | None:
    for p in patterns or []:
        if glob_to_regex(p).match(path):
            return p
    return None


def read_spec(path: Path) -> tuple[dict | None, str]:
    """Return (front matter, full text). Front matter is None when absent, {'__invalid__': True} when broken."""
    text = path.read_text(encoding="utf-8")
    m = FRONT_MATTER.match(text)
    if not m:
        return None, text
    try:
        return yaml.safe_load(m.group(1)) or {}, text
    except yaml.YAMLError:
        return {"__invalid__": True}, text


def permitted_files(spec_text: str) -> list[str]:
    """Paths or globs in the 'Files the agent may change' row of section 7."""
    for line in spec_text.splitlines():
        if re.match(r"^\|\s*Files the agent may change\s*\|", line, re.I):
            return re.findall(r"`([^`]+)`", line)
    return []


def generated_files(spec_text: str) -> list[str]:
    """Paths in the 'Generated files' row of section 7 (C9). The generator command is not a path."""
    for line in spec_text.splitlines():
        if re.match(r"^\|\s*Generated files\s*\|", line, re.I):
            cell = line.split("|")[2] if line.count("|") > 2 else ""
            cell = re.split(r"produced by|generated by", cell, flags=re.I)[0]   # drop the generator command
            return re.findall(r"`([^`<>]+)`", cell)
    return []


def increments(spec_text: str) -> dict[str, dict]:
    """Rows of section 8 'Increments': {ID: {files, estimate, status}}. Template rows are skipped."""
    result, in_section = {}, False
    for line in spec_text.splitlines():
        if line.startswith("## "):
            in_section = bool(re.match(r"^##\s+\d+\.\s+Increments", line))
            continue
        m = re.match(r"^\|\s*(INC-\d+)\s*\|", line) if in_section else None
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        est = re.search(r"\d+", cells[3]) if len(cells) > 3 else None
        result[m.group(1)] = {"files": re.findall(r"`([^`<>]+)`", cells[2]) if len(cells) > 2 else [],
                              "estimate": int(est.group(0)) if est else None,
                              "status": cells[5].lower() if len(cells) > 5 else ""}
    return result


def load_budget(root: Path) -> dict:
    path = root / "policy-config" / "review-budget.yaml"
    return (yaml.safe_load(path.read_text()) or {}) if path.is_file() else {}


def class_rank(name: str) -> int:
    return RISK_CLASSES.index(name)


def load_risk_paths(root: Path) -> dict[str, list[str]]:
    data = yaml.safe_load((root / "policy-config" / "risk-paths.yaml").read_text()) or {}
    return data.get("minimum_class", {})


def minimum_class(files: list[str], risk_paths: dict[str, list[str]]) -> tuple[str, list[tuple[str, str, str]]]:
    """Highest minimum class over the files, and the (file, class, pattern) reasons."""
    best, reasons = "Routine", []
    for f in files:
        for cls in sorted(risk_paths, key=class_rank, reverse=True):
            hit = matches(f, risk_paths[cls])
            if hit:
                reasons.append((f, cls, hit))
                if class_rank(cls) > class_rank(best):
                    best = cls
                break
    return best, reasons


def numstat(base: str, head: str | None, cwd: Path | None = None) -> dict[str, tuple[int, int]]:
    """{path: (added, deleted)}. head None compares base with the working tree. Binary files count 0."""
    rng = [f"{base}...{head}"] if head else [base]
    out = git("diff", "--numstat", "--no-renames", *rng, cwd=cwd)
    result = {}
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) == 3:
            a, d, path = parts
            result[path] = (int(a) if a.isdigit() else 0, int(d) if d.isdigit() else 0)
    return result


def git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout


def changed_files(base: str, head: str, cwd: Path | None = None) -> list[tuple[str, str]]:
    """[(status, path)] between base and head. Status: A, M, D or R (renames report the new path)."""
    out = git("diff", "--name-status", "--no-renames", f"{base}...{head}", cwd=cwd)
    result = []
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) >= 2:
            result.append((parts[0][0], parts[-1]))
    return result
