#!/usr/bin/env python3
"""PreToolUse hook (Claude Code CLI): stop edits outside the active scope (A1) and oversized new files (C9).

The governed-change skill writes the specification path to the first line of
.active-spec, and the increment ID (for example INC-2) to the second line. When
that file exists, this hook permits Edit and Write only on:
  - the files of the active increment (section 8), or of section 7 when the
    increment lists no files,
  - the files under "Generated files" in section 7,
  - the specification folder.
It also stops a Write that creates a new file above max_new_file_lines
(policy-config/review-budget.yaml), unless the file is declared as generated.

When .active-spec does not exist, the hook permits the edit; the permission
rules and plan mode still apply, and CI checks scope and size again
(scripts/check_guardrails.py).

Limits: the hook runs in the Claude Code CLI. The VS Code extension does not run
PreToolUse hooks for all tools, and GitHub Copilot does not read this file.
Shell commands can still write files; the Bash sandbox and CI cover that path.
The hook needs no third-party package, so it reads the YAML value with a pattern.

Exit codes (Claude Code hook protocol): 0 permit, 2 block (stderr goes to the agent).
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path


def glob_to_regex(pattern: str) -> re.Pattern:
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile("^" + out + "$")


def matches(path: str, patterns: list[str]) -> bool:
    return any(glob_to_regex(p).match(path) for p in patterns)


def row_paths(spec_text: str, row: str) -> list[str]:
    for line in spec_text.splitlines():
        if re.match(rf"^\|\s*{re.escape(row)}\s*\|", line, re.I):
            cell = line.split("|")[2] if line.count("|") > 2 else ""
            cell = re.split(r"produced by|generated by", cell, flags=re.I)[0]
            return re.findall(r"`([^`<>]+)`", cell)
    return []


def increment_files(spec_text: str, inc: str) -> list[str]:
    in_section = False
    for line in spec_text.splitlines():
        if line.startswith("## "):
            in_section = bool(re.match(r"^##\s+\d+\.\s+Increments", line))
        elif in_section and re.match(rf"^\|\s*{re.escape(inc)}\s*\|", line, re.I):
            cells = line.strip().strip("|").split("|")
            return re.findall(r"`([^`<>]+)`", cells[2]) if len(cells) > 2 else []
    return []


def max_new_file_lines(root: Path) -> int | None:
    path = root / "policy-config" / "review-budget.yaml"
    if not path.is_file():
        return None
    m = re.search(r"^max_new_file_lines:\s*(\d+)", path.read_text(encoding="utf-8"), re.M)
    return int(m.group(1)) if m else None


def decide(event: dict, root: Path) -> tuple[int, str]:
    active = root / ".active-spec"
    if not active.is_file():
        return 0, ""
    lines = [l.strip() for l in active.read_text(encoding="utf-8").splitlines() if l.strip()]
    spec_rel = lines[0] if lines else ""
    inc = lines[1].upper() if len(lines) > 1 else ""
    spec = root / spec_rel
    if not spec.is_file():
        return 2, f"Scope guard: .active-spec names '{spec_rel}', which does not exist. Ask the user."
    tool_input = event.get("tool_input") or {}
    target = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not target:
        return 0, ""
    try:
        rel = Path(target).resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return 2, f"Scope guard: '{target}' is outside the repository. Specification: {spec_rel}."

    text = spec.read_text(encoding="utf-8")
    generated = row_paths(text, "Generated files")
    scope = (increment_files(text, inc) if inc else []) or row_paths(text, "Files the agent may change")
    where = f"the files of {inc} (section 8)" if inc and increment_files(text, inc) else "section 7"
    if not matches(rel, scope + generated + [f"{Path(spec_rel).parent.as_posix()}/**"]):
        return 2, (f"Scope guard: '{rel}' is not in {where} of {spec_rel}. Do not edit it. "
                   "Ask the user to update the specification, or stop.")

    limit = max_new_file_lines(root)
    content = tool_input.get("content")
    if (event.get("tool_name") == "Write" and content is not None and limit is not None
            and not (root / rel).exists() and not matches(rel, generated)):
        n = len(content.splitlines())
        if n > limit:
            return 2, (f"Size guard (C9): the new file '{rel}' has {n} lines. The limit is {limit} "
                       "(policy-config/review-budget.yaml). Split it into smaller files, or ask the user to "
                       "list it under 'Generated files' in section 7 with its generator. See the "
                       "change-splitter skill.")
    return 0, ""


def main() -> int:
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        return 0
    root = Path(os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or ".")
    code, message = decide(event, root)
    if message:
        print(message, file=sys.stderr)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
